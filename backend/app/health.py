"""Dependency-free health checks for API apps and service entry points.

The module intentionally defines no routes and imports no ORM models. The app can
call ``liveness()``, ``readiness(...)`` and ``dependencies(...)`` from its own
health router without coupling health behavior to API or persistence models.
"""

from __future__ import annotations

import math
import os
import shutil
import sqlite3
import tempfile
import time
from pathlib import Path
from typing import Any, Callable, Iterable, Mapping

Check = dict[str, Any]
HealthReport = dict[str, Any]


def _now_ms() -> int:
    return time.time_ns() // 1_000_000


def _check(name: str, ok: bool | None, *, detail: str | None = None, **values: Any) -> Check:
    state = "ok" if ok is True else "error" if ok is False else "unknown"
    result: Check = {"status": state, "ok": ok}
    if detail:
        result["detail"] = detail
    result.update(values)
    return result


def liveness() -> HealthReport:
    """Return an always-successful process liveness payload for ``/health/live``."""

    return {
        "status": "ok",
        "timestamp_ms": _now_ms(),
        "checks": {"process": _check("process", True)},
    }


def live() -> HealthReport:
    """Short alias for ``liveness``."""

    return liveness()


def _call_check(checker: Any) -> Check:
    """Run a callback or inspect a SQLAlchemy engine without importing app models."""

    if checker is None:
        return _check("database", None, detail="not_configured")
    try:
        if isinstance(checker, sqlite3.Connection):
            checker.execute("SELECT 1").fetchone()
            return _check("database", True, dialect="sqlite")

        if callable(checker):
            result = checker()
            if isinstance(result, Mapping):
                explicit = result.get("ok", result.get("healthy"))
                status = str(result.get("status", result.get("state", ""))).lower()
                if explicit is not None:
                    ok = explicit if isinstance(explicit, bool) else None
                elif status in {"ok", "healthy", "online", "connected", "ready"}:
                    ok = True
                elif status in {"error", "failed", "offline", "disconnected", "unhealthy", "unavailable"}:
                    ok = False
                else:
                    ok = None
                return _check("database", ok, **_safe_details(result))
            return _check("database", bool(result))

        # SQLAlchemy Engine/Connection path; the import remains local so this
        # module can also be used by lightweight CLI/test processes.
        from sqlalchemy import text

        if hasattr(checker, "connect"):
            with checker.connect() as connection:
                connection.execute(text("SELECT 1")).scalar_one()
                dialect = getattr(getattr(connection, "dialect", None), "name", None)
        elif hasattr(checker, "execute"):
            checker.execute(text("SELECT 1")).scalar_one()
            dialect = getattr(getattr(checker, "dialect", None), "name", None)
        else:
            return _check("database", None, detail="unsupported_checker")
        return _check("database", True, dialect=dialect) if dialect else _check("database", True)
    except Exception as exc:
        # Never return raw driver errors; they may contain URLs or credentials.
        return _check("database", False, detail=f"unavailable:{type(exc).__name__}")


def _safe_details(value: Mapping[str, Any]) -> dict[str, Any]:
    allowed = {"dialect", "journal_mode", "foreign_keys", "busy_timeout_ms"}
    return {str(key): item for key, item in value.items() if key in allowed and item is not None}


def check_database(database: Any) -> Check:
    """Check a database callback, SQLAlchemy Engine, or Connection with ``SELECT 1``."""

    result = _call_check(database)
    # Keep the public check key stable regardless of callback implementation.
    return {"database": result}


def check_disk(data_dir: str | os.PathLike[str], *, probe_writable: bool = True) -> Check:
    """Inspect disk space and writable-directory health without exposing its path.

    A small exclusive probe file is created and removed when ``probe_writable`` is
    true; the path is generated by tempfile and never derived from user input.
    Health checks do not create missing application directories.
    """

    path = Path(data_dir).expanduser()
    if not path.exists():
        return {"disk": _check("disk", False, detail="data_directory_missing")}
    if not path.is_dir():
        return {"disk": _check("disk", False, detail="data_path_not_directory")}

    try:
        usage = shutil.disk_usage(path)
    except OSError as exc:
        return {"disk": _check("disk", False, detail=f"stat_failed:{type(exc).__name__}")}

    writable = os.access(path, os.W_OK | os.X_OK)
    if writable and probe_writable:
        probe_name: str | None = None
        descriptor: int | None = None
        try:
            descriptor, probe_name = tempfile.mkstemp(prefix=".health-write-", dir=path)
            os.write(descriptor, b"health")
            os.fsync(descriptor)
        except OSError as exc:
            writable = False
            failure = type(exc).__name__
        else:
            failure = None
        finally:
            if descriptor is not None:
                try:
                    os.close(descriptor)
                except OSError:
                    writable = False
                    failure = failure or "probe_close_failed"
            if probe_name is not None:
                try:
                    os.unlink(probe_name)
                except OSError:
                    # An undeleted health probe is not treated as a healthy write test.
                    writable = False
                    failure = "probe_cleanup_failed"
    else:
        failure = None if writable else "not_writable"

    ok = writable and usage.free > 0
    detail = failure or (None if ok else "disk_full_or_not_writable")
    return {
        "disk": _check(
            "disk",
            ok,
            detail=detail,
            free_bytes=int(usage.free),
            total_bytes=int(usage.total),
        )
    }


def _normalise_status(value: Any, *, dependency_name: str) -> Check:
    if value is None:
        return _check(dependency_name, None, detail="not_configured")
    if isinstance(value, bool):
        return _check(dependency_name, value)
    if callable(value):
        try:
            return _normalise_status(value(), dependency_name=dependency_name)
        except Exception as exc:
            return _check(dependency_name, False, detail=f"probe_failed:{type(exc).__name__}")

    if hasattr(value, "snapshot") and callable(value.snapshot):
        try:
            value = value.snapshot()
        except Exception as exc:
            return _check(dependency_name, False, detail=f"snapshot_failed:{type(exc).__name__}")
    if isinstance(value, Mapping):
        explicit = value.get("ok", value.get("healthy"))
        status = str(value.get("status", value.get("state", ""))).lower()
        if explicit is not None:
            ok = explicit if isinstance(explicit, bool) else None
        elif status in {"ok", "healthy", "online", "connected", "ready", "running"}:
            ok = True
        elif status in {"error", "failed", "offline", "disconnected", "unhealthy", "not_ready", "unavailable"}:
            ok = False
        else:
            ok = None
        safe = {
            str(key): item
            for key, item in value.items()
            if key in {
                "state",
                "status",
                "last_frame_at_ms",
                "last_success_at_ms",
                "last_error_at_ms",
                "frame_count",
                "reconnect_count",
                "consecutive_failures",
                "latency_ms",
            }
            and isinstance(item, (str, int, bool, type(None)))
            or key == "latency_ms" and isinstance(item, float) and math.isfinite(item)
        }
        return _check(dependency_name, ok, **safe)

    status = str(getattr(value, "status", getattr(value, "state", ""))).lower()
    if status:
        return _normalise_status({"status": status}, dependency_name=dependency_name)
    return _check(dependency_name, None, detail="unsupported_status_value")


def _normalise_collection(value: Any, *, dependency_name: str) -> dict[str, Check]:
    if value is None:
        return {}
    if isinstance(value, Mapping):
        items = value.items()
    elif isinstance(value, Iterable) and not isinstance(value, (str, bytes, bytearray)):
        items = ((str(index), item) for index, item in enumerate(value))
    else:
        items = [(dependency_name, value)]
    return {
        str(key): _normalise_status(item, dependency_name=dependency_name)
        for key, item in items
    }


def readiness(
    database: Any,
    data_dir: str | os.PathLike[str],
    migrations_complete: bool | Callable[[], bool],
    worker_configured: bool | Callable[[], bool],
    scheduler_configured: bool | Callable[[], bool],
) -> HealthReport:
    """Build ``/health/ready`` payload.

    Readiness requires database connectivity, completed migrations, a writable data
    volume, and valid worker/scheduler configuration. Camera or AI availability is
    deliberately excluded; those are capability dependencies, not API readiness.
    """

    checks: dict[str, Check] = {}
    checks.update(check_database(database))
    checks.update(check_disk(data_dir))
    checks["migrations"] = _normalise_status(migrations_complete, dependency_name="migrations")
    checks["worker"] = _normalise_status(worker_configured, dependency_name="worker")
    checks["scheduler"] = _normalise_status(scheduler_configured, dependency_name="scheduler")
    ready = all(check.get("ok") is True for check in checks.values())
    return {
        "status": "ready" if ready else "not_ready",
        "timestamp_ms": _now_ms(),
        "checks": checks,
    }


def ready(*args: Any, **kwargs: Any) -> HealthReport:
    """Short alias for :func:`readiness`, accepting positional or keyword inputs."""

    return readiness(*args, **kwargs)


def dependencies(
    database: Any,
    data_dir: str | os.PathLike[str],
    cameras: Any = None,
    ai: Any = None,
    disk_probe_writable: bool = True,
) -> HealthReport:
    """Build a component report for ``/health/dependencies``.

    Camera and AI values should be cached snapshots or quick, bounded probes. AI
    outages mark the report as degraded but do not make API readiness fail.
    """

    checks: dict[str, Any] = {}
    checks.update(check_database(database))
    disk_check = check_disk(data_dir, probe_writable=disk_probe_writable)
    checks.update(disk_check)
    camera_checks = _normalise_collection(cameras, dependency_name="camera")
    ai_checks = _normalise_collection(ai, dependency_name="ai")
    checks["cameras"] = camera_checks
    checks["ai"] = ai_checks

    critical_failed = checks["database"].get("ok") is False or checks["disk"].get("ok") is False
    any_failed = critical_failed or any(
        check.get("ok") is False
        for collection in (camera_checks, ai_checks)
        for check in collection.values()
    )
    unknown = any(
        check.get("ok") is None
        for check in (
            checks["database"],
            checks["disk"],
            *camera_checks.values(),
            *ai_checks.values(),
        )
    )
    status = "unavailable" if critical_failed else "degraded" if any_failed or unknown else "ok"
    return {"status": status, "timestamp_ms": _now_ms(), "checks": checks}


def check_dependencies(*args: Any, **kwargs: Any) -> HealthReport:
    return dependencies(*args, **kwargs)


def http_status(report: Mapping[str, Any], *, endpoint: str) -> int:
    """Return conventional HTTP status for an app-owned health route.

    Liveness is always 200. Readiness is 503 unless status is ``ready``. Dependency
    reports remain 200 when only cameras or AI are degraded, but return 503 if DB or
    disk is unavailable.
    """

    if endpoint in {"live", "liveness", "/health/live"}:
        return 200
    status = report.get("status")
    if endpoint in {"ready", "readiness", "/health/ready"}:
        return 200 if status == "ready" else 503
    if endpoint in {"dependencies", "/health/dependencies"}:
        return 503 if status == "unavailable" else 200
    raise ValueError(f"unknown health endpoint: {endpoint}")


def health_response(report: Mapping[str, Any], *, endpoint: str) -> tuple[int, dict[str, Any]]:
    """Return ``(status_code, body)`` for convenient FastAPI JSONResponse usage."""

    return http_status(report, endpoint=endpoint), dict(report)



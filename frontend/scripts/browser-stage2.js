async (page) => {
  const checks=[],base='http://127.0.0.1:5173';
  const assert=(ok,message)=>{if(!ok)throw new Error(message);checks.push(message);};
  const state=await(await page.request.get(base+'/api/_test/state')).json();
  const cameraState=async id=>(await(await page.request.get(base+'/api/cameras/'+id)).json()).data;
  const waitCamera=async(id,predicate)=>{for(let i=0;i<35;i++){const c=await cameraState(id);if(c&&predicate(c))return c;await page.waitForTimeout(500);}throw new Error('等待实际摄像头状态超时');};
  const saveImpact=async()=>{await page.getByRole('button',{name:'保存机位配置',exact:true}).click();const dialog=page.getByRole('dialog',{name:'确认机位配置影响',exact:true});await dialog.waitFor();await dialog.getByRole('button',{name:'确认保存',exact:true}).click();await dialog.waitFor({state:'hidden'});};
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/cameras/'+state.camera);
  await page.getByRole('button',{name:'临时停止',exact:true}).waitFor();
  await page.getByRole('button',{name:'临时停止',exact:true}).click();
  const stop=page.getByRole('dialog',{name:'临时停止采集',exact:true});await stop.waitFor();
  const expires=await stop.locator('input[type="datetime-local"]').inputValue();
  assert(expires.includes('12:00'),'F03 临时停止默认结束于下一北京时间计划边界');
  await stop.getByRole('button',{name:'确认临时停止',exact:true}).click();
  const paused=await waitCamera(state.camera,c=>c.runtime.capture_state==='stopped'&&c.runtime.stop_reason==='manual_override');
  assert(paused.enabled&&paused.runtime.override_expires_at,'F03 临停保持启用，后台实际应用已确认');
  await page.reload();await page.getByRole('button',{name:'恢复计划',exact:true}).waitFor();
  assert((await page.locator('.page-heading').innerText()).includes('已临时停止'),'F03 刷新后临时覆盖状态仍可读');
  await page.getByRole('button',{name:'恢复计划',exact:true}).click();
  await page.getByRole('dialog',{name:'恢复周计划',exact:true}).getByRole('button',{name:'确认恢复计划',exact:true}).click();
  const resumed=await waitCamera(state.camera,c=>c.runtime.capture_state==='online'&&!c.runtime.override_mode);
  assert(resumed.runtime.applied_revision===resumed.runtime.control_revision,'F03 恢复计划后实际采集与控制版本一致');
  // A second camera must pass the single-camera trial gate before multi-camera capacity is known.
  await page.reload();
  await page.getByRole('checkbox',{name:/启用机位/}).uncheck();await saveImpact();
  await waitCamera(state.camera,c=>!c.enabled);
  await page.goto(base+'/cameras/new');
  await page.getByLabel('机位名称',{exact:true}).fill('浏览器验收临时机位');
  await page.getByLabel('允许的本机端口',{exact:true}).fill(String(state.rtsp_port));
  await page.getByRole('button',{name:'保存停用草稿',exact:true}).click();
  await page.waitForURL(/\/cameras\/cam_/);
  const id=new URL(page.url()).pathname.split('/').at(-1);
  assert(!(await cameraState(id)).enabled,'F02 添加先持久保存为停用草稿');
  await page.getByRole('button',{name:'测试已保存的视频来源',exact:true}).click();
  const job=page.getByRole('dialog',{name:'任务进度',exact:true});await job.waitFor();
  await job.getByText('已完成',{exact:true}).waitFor({timeout:25000});
  await job.getByRole('button',{name:'关闭对话框',exact:true}).click();
  const tested=await cameraState(id);
  assert(tested.last_test&&tested.last_test.codec==='h264'&&!tested.enabled,'F02 实际 RTSP 连接测试得到编码与图片，未自动启用');
  await page.getByRole('button',{name:'增加时段',exact:true}).click();
  await page.getByRole('button',{name:'编辑包含区 / 排除区',exact:true}).click();
  await page.locator('.roi-stage img').waitFor();
  const box=await page.locator('.roi-stage svg').boundingBox();
  await page.mouse.move(box.x+box.width*.4,box.y+box.height*.3);await page.mouse.down();await page.mouse.move(box.x+box.width*.6,box.y+box.height*.7,{steps:8});await page.mouse.up();
  await page.locator('.roi-region-list button').first().waitFor();
  await page.getByRole('checkbox',{name:/启用机位/}).check();
  await saveImpact();
  const online=await waitCamera(id,c=>c.runtime.capture_state==='online');
  assert(online.enabled&&online.regions.include.length===1,'F02 周计划、归一化 ROI、预检启用与实际开始均完成');
  const minutes=await(await page.request.get(base+'/api/minutes',{params:{from:'2026-10-17T16:00:00Z',to:'2026-10-18T16:00:00Z',camera_id:id}})).json();
  assert(minutes.data.length>0,'F02 启用后出现真实采集的第一条分钟记录');
  await page.screenshot({path:'output/playwright/camera-390.png',fullPage:true});
  await page.getByRole('button',{name:'删除机位',exact:true}).click();
  await page.getByRole('dialog',{name:/删除「浏览器验收临时机位/}).getByRole('button',{name:'删除机位并保留历史',exact:true}).click();
  await page.getByRole('dialog',{name:'任务进度',exact:true}).getByText('已完成',{exact:true}).waitFor();
  await page.getByRole('dialog',{name:'任务进度',exact:true}).getByRole('button',{name:'关闭对话框',exact:true}).click();
  await page.waitForURL(/\/cameras(?:\?|$)/);
  const history=await(await page.request.get(base+'/api/minutes/'+minutes.data[0].id)).json();
  assert(history.data.id===minutes.data[0].id,'F02 删除机位后历史分钟记录继续可访问');
  await page.goto(base+'/cameras/'+state.camera);
  await page.getByRole('checkbox',{name:/启用机位/}).check();await saveImpact();
  await waitCamera(state.camera,c=>c.runtime.capture_state==='online');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'F13 390px 完整机位表单无横向溢出');
  return {checks};
}
